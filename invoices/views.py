# ✅ Generic invoice list view for sidebar
@login_required
def invoice_list(request):
    invoices = (
        Invoice.objects
        .select_related("customer", "motorcycle", "agent")
        .order_by("-created_at")
    )
    return render(request, 'invoices/invoice_list.html', {'invoices': invoices})


# ✅ Invoice dashboard view with categorized querysets
@login_required
def invoice_dashboard(request):
    invoices = (
        Invoice.objects
        .select_related("customer", "motorcycle", "agent")
        .annotate(
            agg_last_payment_date=Max("payments__timestamp")   # ✅ renamed to avoid property clash
        )
    )

    context = {
        "pending_invoices": invoices.filter(status="PENDING"),
        "paid_invoices": invoices.filter(status="PAID"),
        "partial_invoices": invoices.filter(status="PARTIAL"),
        "overdue_invoices": invoices.filter(status="OVERDUE"),
        "defaulted_invoices": invoices.filter(status="DEFAULTED"),
        "failed_invoices": invoices.filter(status="FAILED"),
    }
    return render(request, "invoices/invoice_dashboard.html", context)


# ✅ Successful invoices list (all except FAILED)
@login_required
def successful_invoices(request):
    invoices = (
        Invoice.objects
        .exclude(status="FAILED")
        .select_related("customer", "motorcycle", "agent")
        .annotate(
            agg_last_payment_date=Max("payments__timestamp")   # ✅ renamed to avoid property clash
        )
    )

    enriched_invoices = []
    for inv in invoices:
        commission = inv.agent_commission if inv.agent else None
        payment_status = "Settled" if inv.balance_remaining == 0 else f"Balance Remaining: {inv.balance_remaining} TZS"

        enriched_invoices.append({
            "invoice": inv,
            "commission": commission,
            "payment_status": payment_status,
        })

    return render(request, "invoices/successful_invoices.html", {"enriched_invoices": enriched_invoices})


# ✅ Failed invoices list (with reconciliation details)
@login_required
def failed_invoices(request):
    failed_logs = InvoiceLog.objects.filter(status="FAILED").order_by("-created_on")
    return render(request, "invoices/failed_invoices.html", {"failed_logs": failed_logs})


# ✅ Helper to check if user can regenerate
def can_regenerate(user):
    return getattr(user, "is_admin", False) or getattr(user, "is_manager", False) or getattr(user, "is_officer", False)


# ✅ Re-generate failed invoice with notifications
@login_required
@user_passes_test(can_regenerate)
def regenerate_invoice(request, invoice_id):
    invoice = get_object_or_404(Invoice, invoice_id=invoice_id)

    if invoice.status == "FAILED":
        try:
            invoice.status = "PENDING"
            invoice.save()

            # ✅ Log regeneration action distinctly
            InvoiceLog.objects.create(
                invoice=invoice,
                status="REGENERATED",
                reason="Invoice re-generated by admin/manager/officer",
                customer_id=invoice.customer.customer_id if invoice.customer else None,
                customer_name=invoice.customer.full_name if invoice.customer else None,
                motorcycle_vin=invoice.motorcycle.vin if invoice.motorcycle else None,
                amount=invoice.amount_due
            )

            # ✅ Notify customer
            if invoice.customer and invoice.customer.email:
                NotificationLog.objects.create(
                    recipient=invoice.customer.email,
                    message=f"Dear {invoice.customer.full_name}, your invoice {invoice.invoice_id} has been re-generated and is now pending."
                )

            # ✅ Notify agent
            if invoice.agent and invoice.agent.email:
                NotificationLog.objects.create(
                    recipient=invoice.agent.email,
                    message=f"Invoice {invoice.invoice_id} for customer {invoice.customer.full_name} has been re-generated."
                )

            # ✅ Notify officer in charge
            if hasattr(invoice.customer, "officer_in_charge") and invoice.customer.officer_in_charge and invoice.customer.officer_in_charge.email:
                NotificationLog.objects.create(
                    recipient=invoice.customer.officer_in_charge.email,
                    message=f"Invoice {invoice.invoice_id} linked to motorcycle {invoice.motorcycle.vin if invoice.motorcycle else 'N/A'} has been re-generated."
                )

            messages.success(request, f"Invoice {invoice.invoice_id} re-generated successfully and notifications sent.")
        except Exception as e:
            messages.error(request, f"Failed to re-generate invoice {invoice.invoice_id}: {str(e)}")
    else:
        messages.warning(request, f"Invoice {invoice.invoice_id} is not marked as FAILED.")

    return redirect("failed_invoices")


# ✅ Selcom webhook handler with success/failure logging
@csrf_exempt
def selcom_webhook(request):
    if request.method == 'POST':
        try:
            data = json.loads(request.body)
        except json.JSONDecodeError:
            return JsonResponse({"status": "error", "message": "Invalid JSON"}, status=400)

        invoice_id = data.get('invoice_id')
        amount = data.get('amount')
        transaction_id = data.get('transaction_id')
        status = data.get('status')   # ✅ Selcom should send SUCCESS/FAILED
        reason = data.get('reason')   # ✅ e.g. "Insufficient funds"

        try:
            invoice = Invoice.objects.get(invoice_id=invoice_id)

            if status == "SUCCESS":
                # ✅ Record payment
                Payment.objects.create(
                    invoice=invoice,
                    amount_paid=amount,
                    transaction_id=transaction_id
                )

                # ✅ Update invoice status using properties
                if invoice.total_paid >= invoice.amount_due:
                    invoice.status = 'PAID'
                elif invoice.total_paid > 0:
                    invoice.status = 'PARTIAL'
                invoice.save()

                # ✅ Reduce customer balance
                customer = invoice.customer
                if hasattr(customer, "reduce_balance"):
                    customer.reduce_balance(amount)

                # ✅ Log success
                PaymentLog.objects.create(
                    invoice=invoice,
                    transaction_id=transaction_id,
                    status="SUCCESS",
                    amount=amount,
                    customer_name=invoice.customer.full_name,
                    motorcycle_vin=invoice.motorcycle.vin if invoice.motorcycle else None
                )
                return JsonResponse({"status": "success"})

            else:  # FAILED
                # ✅ Log failure with reason
                PaymentLog.objects.create(
                    invoice=invoice,
                    transaction_id=transaction_id,
                    status="FAILED",
                    reason=reason,
                    amount=amount,
                    customer_name=invoice.customer.full_name if invoice.customer else None,
                    motorcycle_vin=invoice.motorcycle.vin if invoice.motorcycle else None
                )
                return JsonResponse({"status": "failed", "reason": reason}, status=400)

        except Invoice.DoesNotExist:
            return JsonResponse({"status": "error", "message": "Invoice not found"}, status=404)

    return JsonResponse({"status": "error", "message": "Invalid request method"}, status=405)
